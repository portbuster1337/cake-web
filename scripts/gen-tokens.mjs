// Generates src/coins/tokens.gen.ts from Cake Wallet's default token lists:
// cw_evm/lib/tokens/*_tokens.dart, cw_solana/lib/default_spl_tokens.dart,
// cw_tron/lib/default_tron_tokens.dart.
//   node scripts/gen-tokens.mjs [path/to/cake_wallet]
import fs from 'node:fs';
import path from 'node:path';

const cake = process.argv[2] || path.resolve('../cake-refs/cake_wallet');
const out = path.resolve('src/coins/tokens.gen.ts');

function blocks(src, ctor) {
  const res = [];
  let i = 0;
  for (;;) {
    const at = src.indexOf(`${ctor}(`, i);
    if (at < 0) break;
    let depth = 0;
    let j = at + ctor.length;
    for (; j < src.length; j++) {
      if (src[j] === '(') depth++;
      else if (src[j] === ')') {
        depth--;
        if (depth === 0) break;
      }
    }
    res.push(src.slice(at + ctor.length + 1, j));
    i = j;
  }
  return res;
}

function field(b, name) {
  const m = new RegExp(`\\b${name}:\\s*(?:"([^"]*)"|'([^']*)'|([\\w.]+))`).exec(b);
  if (!m) return undefined;
  return m[1] ?? m[2] ?? m[3];
}

function groups(b) {
  const m = /groups:\s*const\s*\{([^}]*)\}/.exec(b) || /groups:\s*\{([^}]*)\}/.exec(b);
  if (!m) return undefined;
  const g = m[1].split(',').map((x) => x.trim().replace(/^CurrencyGroups\./, '')).filter(Boolean);
  return g.length ? g : undefined;
}

function parse(file, ctor, addrField) {
  const src = fs.readFileSync(path.join(cake, file), 'utf8');
  return blocks(src, ctor)
    .map((b) => {
      const t = {
        name: field(b, 'name'),
        symbol: field(b, 'symbol'),
        address: field(b, addrField),
        decimals: Number(field(b, 'decimal')),
        enabled: field(b, 'enabled') === 'true',
      };
      const icon = field(b, 'iconPath');
      if (icon) t.icon = icon;
      const mint = field(b, 'mint');
      if (mint) t.mint = mint;
      const g = groups(b);
      if (g) t.groups = g;
      return t;
    })
    .filter((t) => t.address && t.symbol);
}

const EVM = [
  ['ethereum', 'ethereum_tokens.dart', 'ETH'],
  ['polygon', 'polygon_tokens.dart', 'POL'],
  ['base', 'base_tokens.dart', 'BASE'],
  ['arbitrum', 'arbitrum_tokens.dart', 'ARB'],
  ['bsc', 'bsc_tokens.dart', 'BSC'],
  ['robinhood', 'robinhood_tokens.dart', 'ROB'],
];

const evm = {};
for (const [type, file] of EVM) evm[type] = parse(`cw_evm/lib/tokens/${file}`, 'Erc20Token', 'contractAddress');
const spl = parse('cw_solana/lib/default_spl_tokens.dart', 'SPLToken', 'mintAddress');
const trc = parse('cw_tron/lib/default_tron_tokens.dart', 'TronToken', 'contractAddress');

const header = `// GENERATED by scripts/gen-tokens.mjs from Cake Wallet's default token lists
// (cw_evm/lib/tokens/*.dart, cw_solana/lib/default_spl_tokens.dart, cw_tron/lib/default_tron_tokens.dart). Do not edit.
export interface DefaultToken {
  name: string;
  symbol: string;
  /** contract (EVM/Tron) or mint (Solana) address, as written by Cake */
  address: string;
  decimals: number;
  /** enabled by default */
  enabled: boolean;
  icon?: string;
  /** Solana short code */
  mint?: string;
  groups?: string[];
}
`;
const body =
  `export const EVM_DEFAULT_TOKENS: Record<string, DefaultToken[]> = ${JSON.stringify(evm)};\n` +
  `export const EVM_TOKEN_TAGS: Record<string, string> = ${JSON.stringify(Object.fromEntries(EVM.map(([t, , tag]) => [t, tag])))};\n` +
  `export const SPL_DEFAULT_TOKENS: DefaultToken[] = ${JSON.stringify(spl)};\n` +
  `export const TRON_DEFAULT_TOKENS: DefaultToken[] = ${JSON.stringify(trc)};\n`;
fs.writeFileSync(out, header + body);
console.log('wrote', out, Object.fromEntries(Object.entries(evm).map(([k, v]) => [k, v.length])), 'spl', spl.length, 'trc20', trc.length);
