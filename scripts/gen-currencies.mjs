// Generates src/coins/currencies.gen.ts from Cake Wallet's
// cw_core/lib/crypto_currency.dart (the list of every currency the app knows:
// wallet coins, tokens and exchange-only currencies), so names, tickers,
// networks (tags), decimals and icons match the official app exactly.
//   node scripts/gen-currencies.mjs [path/to/cake_wallet]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const cake = process.argv[2] || path.join(root, '..', 'cake-refs', 'cake_wallet');
const src = fs.readFileSync(path.join(cake, 'cw_core/lib/crypto_currency.dart'), 'utf8');

function parseArgs(body) {
  const out = {};
  const re = /(\w+)\s*:\s*((?:const\s*)?\{[^}]*\}|'[^']*'|"[^"]*"|[^,)]+)/g;
  let m;
  while ((m = re.exec(body))) {
    let v = m[2].trim();
    if (/^'.*'$|^".*"$/.test(v)) v = v.slice(1, -1);
    else if (/^(const\s*)?\{/.test(v)) v = v.replace(/^const\s*/, '').slice(1, -1).split(',').map((s) => s.trim().replace(/^CurrencyGroups\./, '')).filter(Boolean);
    else if (/^-?\d+$/.test(v)) v = Number(v);
    else if (v === 'true' || v === 'false') v = v === 'true';
    out[m[1]] = v;
  }
  return out;
}

const defs = {};
const re = /static const (\w+)\s*=\s*CryptoCurrency\(([\s\S]*?)\);/g;
let m;
while ((m = re.exec(src))) defs[m[1]] = parseArgs(m[2]);

function list(name) {
  const r = new RegExp(`static const ${name}\\s*=\\s*\\[([\\s\\S]*?)\\];`).exec(src);
  if (!r) throw new Error(`no list ${name}`);
  return r[1].split(',').map((s) => s.trim().replace(/^CryptoCurrency\./, '')).filter(Boolean);
}

const all = list('all');
const haven = list('havenCurrencies');
const zcash = list('zcashCurrencies');
const rows = [];
for (const key of [...new Set([...all, ...haven, ...zcash])]) {
  const d = defs[key];
  if (!d) throw new Error(`missing definition for ${key}`);
  rows.push({
    key,
    title: d.title,
    tag: d.tag ?? null,
    fullName: d.fullName ?? null,
    raw: d.raw,
    name: d.name,
    decimals: d.decimals,
    iconPath: d.iconPath ?? null,
    flatIconPath: d.flatIconPath ?? null,
    chainIconPath: d.chainIconPath ?? null,
    groups: d.groups ?? [],
    isPotentialScam: !!d.isPotentialScam,
    inAll: all.includes(key),
  });
}

const schemeBlock = /_schemeCurrencyMap = \{([\s\S]*?)\};/.exec(src)[1];
const schemes = {};
for (const s of schemeBlock.matchAll(/['"]([\w-]+)['"]\s*:\s*(\w+)/g)) schemes[s[1]] = s[2];

const out = `// GENERATED by scripts/gen-currencies.mjs from Cake Wallet cw_core/lib/crypto_currency.dart. Do not edit.
export interface CurrencyDef {
  key: string; title: string; tag: string | null; fullName: string | null; raw: number; name: string; decimals: number;
  iconPath: string | null; flatIconPath: string | null; chainIconPath: string | null; groups: string[]; isPotentialScam: boolean; inAll: boolean;
}
export const CURRENCY_DEFS: CurrencyDef[] = ${JSON.stringify(rows, null, 0).replace(/\},\{/g, '},\n  {')};
export const SCHEME_CURRENCY: Record<string, string> = ${JSON.stringify(schemes)};
`;
fs.writeFileSync(path.join(root, 'src/coins/currencies.gen.ts'), out);
console.log(`wrote ${rows.length} currencies (${all.length} in CryptoCurrency.all)`);
